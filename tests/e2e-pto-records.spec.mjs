import {test,expect} from '@playwright/test';
test('PTO registers link evidence to acts and persist Russian entries after reload',async({page})=>{
 const failures=[];page.on('pageerror',e=>failures.push(e.message));
 await page.goto('http://127.0.0.1:3042/');
 await page.locator('[data-tab="pto"]').click();
 await page.locator('#pto-sample').click();
 const section=page.locator('#pto-field-registers');
 await expect(section).toContainText('журнал общих работ');
 await section.locator('[data-record-add="journal"]').click();
 await section.locator('.pto-record-area').nth(0).locator('input[type=date]').fill('2026-10-10');
 await section.locator('.pto-record-area').nth(0).locator('input[type=text]').nth(0).fill('1.0');
 await section.locator('.pto-record-area').nth(0).locator('textarea').fill('Тестовая запись ОЖР');
 await section.locator('.pto-record-area').nth(0).locator('input[type=text]').nth(1).fill('ОЖР стр. 3');
 await section.locator('[data-record-add="documents"]').click();
 const quality=section.locator('.pto-record-area').nth(1);
 await quality.locator('input[type=text]').nth(0).fill('1.0');
 await quality.locator('input[type=text]').nth(1).fill('Паспорт');
 await quality.locator('input[type=text]').nth(2).fill('TEST-001');
 await quality.locator('textarea').fill('Мембрана');
 await quality.locator('input[type=text]').last().fill('passport.pdf');
 await section.locator('[data-record-add="schemes"]').click();
 const scheme=section.locator('.pto-record-area').nth(2);
 await scheme.locator('input[type=text]').nth(0).fill('1.0');
 await scheme.locator('input[type=text]').nth(1).fill('ИС-01');
 await scheme.locator('input[type=text]').last().fill('scheme.pdf');
 await expect(section.locator('#pto-readiness-rows tr').first()).toContainText('1.0');
 await expect(section.locator('#pto-readiness-rows tr').first()).toContainText('1');
 await page.reload();
 await page.locator('[data-tab="pto"]').click();
 await expect(page.locator('.pto-record-area').nth(1).locator('input[type=text]').nth(2)).toHaveValue('TEST-001');
 await expect(page.locator('.pto-record-area').nth(0).locator('input[type=text]').nth(1)).toHaveValue('ОЖР стр. 3');
 const [csv]=await Promise.all([page.waitForEvent('download'),section.locator('#pto-readiness-export').click()]);
 expect(csv.suggestedFilename()).toBe('pto_readiness.csv');
 expect(failures).toEqual([]);
});
