import {test,expect} from '@playwright/test';

test('Russian quick AOSR entry edits only requested groups and preserves all advanced values',async({page})=>{
 const errors=[];page.on('pageerror',err=>errors.push(err.message));
 await page.goto('http://127.0.0.1:3042/');
 await page.locator('[data-tab="pto"]').click();
 await expect(page.locator('#pto-quick-mode')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#pto-quick-editor')).toBeVisible();
 await expect(page.locator('#pto-full-editor')).toBeHidden();
 await expect(page.locator('#pto-quick-acts details')).toHaveCount(15);
 await page.locator('#pto-sample').click();
 const first=page.locator('#pto-quick-acts details').first();
 await expect(first).toHaveAttribute('open','');
 await expect(first.locator('[data-field="schemeNo"]')).toHaveValue('ИС-01');
 await expect(first).toContainText('ИС-01');
 await expect(first).toContainText('НЕ подтверждено');
 await first.locator('[data-field="work"]').fill('ДЕМОНСТРАЦИЯ: гидроизоляция кровли, секция С');
 await first.locator('[data-field="start"]').fill('2026-10-07');
 await first.locator('[data-field="end"]').fill('2026-10-09');
 await first.locator('[data-field="actDate"]').fill('2026-10-10');
 await first.locator('[data-field="schemeNo"]').fill('ИС-ПРОВЕРКА-01');
 await first.locator('[data-field="qualityDocs"]').fill('Паспорт материала DEMO-1; сертификат DEMO-2');
 await expect(first.locator('summary')).toContainText('секция С');
 await page.locator('#pto-full-mode').click();
 await expect(page.locator('#pto-quick-editor')).toBeHidden();
 await expect(page.locator('#pto-full-editor')).toBeVisible();
 const full=page.locator('#pto-act-rows tr').first();
 await expect(full.locator('[data-col="work"]')).toHaveValue('ДЕМОНСТРАЦИЯ: гидроизоляция кровли, секция С');
 await expect(full.locator('[data-col="schemeNo"]')).toHaveValue('ИС-ПРОВЕРКА-01');
 await expect(full.locator('[data-col="qualityDocs"]')).toHaveValue('Паспорт материала DEMO-1; сертификат DEMO-2');
 await expect(full.locator('[data-col="start"]')).toHaveValue('2026-10-07');
 const unchangedQty=await full.locator('[data-col="measuredQty"]').inputValue();
 await full.locator('[data-col="measuredQty"]').fill('19,25');
 await page.locator('#pto-quick-mode').click();
 await expect(page.locator('#pto-quick-acts details').first().locator('[data-field="work"]')).toHaveValue('ДЕМОНСТРАЦИЯ: гидроизоляция кровли, секция С');
 await page.reload();await page.locator('[data-tab="pto"]').click();
 await expect(page.locator('#pto-quick-mode')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#pto-quick-acts details').first().locator('[data-field="schemeNo"]')).toHaveValue('ИС-ПРОВЕРКА-01');
 await page.locator('#pto-full-mode').click();
 await expect(page.locator('#pto-act-rows tr').first().locator('[data-col="measuredQty"]')).toHaveValue('19,25');
 expect(unchangedQty).not.toBe('');
 expect(errors).toEqual([]);
});
